def curve_average(curves, length, min_draws=1):
    a = np.asarray(curves, dtype=float)
    if a.size == 0: return np.full(length, np.nan), 0
    if a.ndim != 2 or a.shape[1] != length: raise ValueError("Unexpected curve shape.")
    valid = np.isfinite(a).all(axis=1)
    n = int(valid.sum())
    return (np.mean(a[valid], axis=0), n) if n >= min_draws else (np.full(length, np.nan), n)


