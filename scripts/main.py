def geometry_and_pca(X):
    X = validate_trials(X)
    flat = StandardScaler().fit_transform(X.reshape(-1, X.shape[-1]))
    flat -= flat.mean(axis=0)
    s = np.linalg.svd(flat, full_matrices=False, compute_uv=False)
    variance = s ** 2
    if variance.sum() <= VAR_EPS: return np.nan, np.full(X.shape[-1], np.nan)
    fractions = variance / variance.sum()
    pr = float(1.0 / np.sum(fractions ** 2))
    cumulative = np.full(X.shape[-1], np.nan)
    cumulative[:len(fractions)] = np.cumsum(fractions)
    return pr, cumulative

def compute_identity_averaged_stats(X_by_identity):
    X = np.asarray(X_by_identity, dtype=np.float64)
    if X.ndim != 4 or X.shape[1] < 2 or not np.isfinite(X).all(): raise ValueError("Invalid identity-by-repeat array.")
    counts = X.sum(axis=2)
    means = counts.mean(axis=1)
    variance = counts.var(axis=1, ddof=1)
    valid_fano = means > 0
    fano = float(np.mean(variance[valid_fano] / means[valid_fano])) if valid_fano.any() else np.nan
    snr_results = []
    for identity in X:
        signal_var = np.var(identity.mean(axis=0), axis=0, ddof=0)
        noise_var = np.mean(np.var(identity, axis=0, ddof=0), axis=0)
        usable = noise_var > 1e-8
        snr = float(np.mean(signal_var[usable] / noise_var[usable])) if usable.any() else np.nan
        snr_results.append((snr, int(usable.sum())))
    snr_mean, _, snr_n = mean_sd_n([item[0] for item in snr_results])
    return {"fano": fano, "fr": float(counts.mean() / ANALYSIS_WINDOW_S),
            "snr": snr_mean, "fano_valid_identity_neuron_pairs": int(valid_fano.sum()),
            "snr_valid_identities": snr_n, "snr_valid_identity_neuron_pairs": sum(item[1] for item in snr_results)}

def compute_identity_acf(X_by_identity, max_lag):
    if max_lag < 0: raise ValueError("max_lag must be nonnegative.")
    curves, neuron_counts = [], []
    for identity in X_by_identity:
        X = validate_trials(identity)
        R, T, N = X.shape
        L = min(int(max_lag), T - 1)
        centered = X - X.mean(axis=(0, 1), keepdims=True)
        variance = np.mean(centered ** 2, axis=(0, 1))
        valid = variance >= 1e-6
        if not valid.any(): continue
        centered, variance = centered[:, :, valid], variance[valid]
        curve = np.empty(L + 1)
        for lag in range(L + 1):
            covariance = np.mean(centered[:, :T - lag, :] * centered[:, lag:, :], axis=(0, 1))
            curve[lag] = np.mean(covariance / variance)
        curves.append(curve)
        neuron_counts.append(int(valid.sum()))
    if not curves: return np.full(min(max_lag, X_by_identity.shape[2] - 1) + 1, np.nan), 0, 0
    return np.mean(curves, axis=0), len(curves), sum(neuron_counts)


