    for key, frame in stat.items():
        if frame["fdr_scheme"].ne(FDR_SCHEME).any(): raise RuntimeError(f"Unclassified statistical rows in {key}.")
    for key in FDR_STAT_TABLE_KEYS: tables[key] = stat[key]
    if neuron_tables:
        neuron_tables[OUTPUT_FILES["neuron_count"]["summary"]] = stat["nc_summary"]
        neuron_tables[OUTPUT_FILES["neuron_count"]["correlations"]] = stat["nc_correlations"]
    family_summary = pd.DataFrame(family_rows)
    print("\nSix-family multiplicity summary (unique finite hypotheses):")
    print(family_summary[["fdr_family", "n_finite_tests", "n_duplicate_rows_within_family", "n_reference_rows_reusing_other_family"]].to_string(index=False))
