def rank_residual_rho(values):
    a = np.asarray(values, dtype=float)
    n, p = a.shape
    k = p - 2
    if n < k + 4 or not np.isfinite(a).all(): return np.nan
    ranked = rankdata(a, axis=0, method="average")
    design = np.column_stack([np.ones(n), ranked[:, 2:]])
    if np.linalg.matrix_rank(design) != k + 1: return np.nan
    residual = ranked[:, :2] - design @ np.linalg.lstsq(design, ranked[:, :2], rcond=None)[0]
    ss = np.sum(residual ** 2, axis=0)
    if np.any(ss <= VAR_EPS): return np.nan
    return float(np.clip(np.sum(residual[:, 0] * residual[:, 1]) / np.sqrt(ss.prod()), -1, 1))

def partial_spearman_result(data, x, y, covars, n_boot=N_CI_BOOTSTRAPS, seed=42):
    columns = [x, y] + list(covars)
    d = finite_frame(data, columns)
    a = d.to_numpy(dtype=float)
    rho = rank_residual_rho(a) if len(d) else np.nan
    result = {"rho": rho, "p": np.nan, "ci95_low": np.nan, "ci95_high": np.nan, "n_sessions": len(d),
              "n_boot_requested": n_boot, "n_boot_valid": 0, "ci_valid_fraction": np.nan,
              "ci_method": "session_bootstrap_percentile_pointwise", "status": "ok"}
    if not np.isfinite(rho):
        result["status"] = "insufficient_sample_or_degenerate_rank_residuals"
        return result
    dof = len(d) - len(covars) - 2
    tval = rho * np.sqrt(dof / max(1 - rho ** 2, np.finfo(float).tiny))
    result["p"] = float(2 * student_t.sf(abs(tval), dof))
    if n_boot <= 0:
        result["status"] = "ci_not_requested"
        return result
    rng = np.random.RandomState(seed)
    n, p = a.shape
    out = []
    for start in range(0, n_boot, 512):
        size = min(512, n_boot - start)
        indices = rng.randint(0, n, size=(size, n))
        if p <= 3:
            ranks = rankdata(a[indices], axis=1, method="average")
            ranks -= ranks.mean(axis=1, keepdims=True)
            residual = ranks[:, :, :2].copy()
            valid = np.ones(size, dtype=bool)
            if p == 3:
                cov = ranks[:, :, 2]
                denominator = np.sum(cov ** 2, axis=1)
                valid &= denominator > VAR_EPS
                denom_safe = np.where(valid, denominator, 1.0)
                beta = np.sum(residual * cov[:, :, None], axis=1) / denom_safe[:, None]
                residual -= cov[:, :, None] * beta[:, None, :]
            ss = np.sum(residual ** 2, axis=1)
            valid &= np.all(ss > VAR_EPS, axis=1)
            with np.errstate(divide="ignore", invalid="ignore"):
                r = np.sum(residual[:, :, 0] * residual[:, :, 1], axis=1) / np.sqrt(ss[:, 0] * ss[:, 1])
            out.extend(np.clip(r[valid & np.isfinite(r)], -1, 1))
        else:
            for idx in indices:
                value = rank_residual_rho(a[idx])
                if np.isfinite(value): out.append(value)
    boots = np.asarray(out)
    result["n_boot_valid"] = len(boots)
    result["ci_valid_fraction"] = len(boots) / n_boot
    if len(boots) < MIN_CI_VALID_FRACTION * n_boot:
        result["status"] = "too_few_valid_ci_draws"
        warnings.warn(f"CI unavailable for {x} versus {y}: {len(boots)}/{n_boot} valid draws.")
    else:
        result["ci95_low"], result["ci95_high"] = np.percentile(boots, [2.5, 97.5]).tolist()
    return result

def run_dim_tau_correlation(df, x, y, covars, bin_ms, condition, metric, seed, rank=np.nan, top_k=np.nan):
    r = partial_spearman_result(df, x, y, covars, N_CI_BOOTSTRAPS, seed)
    return {"bin_ms": bin_ms, "condition": condition, "metric": metric, "rank": rank, "top_k": top_k, "x_column": x, "y_column": y, "covariates": "|".join(covars), **r}

def append_paired_t_summary(df_per, rows, metric, col_g, col_m):
    d = finite_frame(df_per, [col_g, col_m])
    g, m = d[col_g].to_numpy(), d[col_m].to_numpy()
    gm, gs = mean_sem(g)
    mm, ms = mean_sem(m)
    tval, p = np.nan, np.nan
    status = "ok"
    if len(d) < 2: status = "insufficient_pairs"
    elif np.all(m == g): tval, p = 0.0, 1.0
    elif np.std(m - g, ddof=1) <= VAR_EPS: status = "constant_nonzero_difference"
    else: tval, p = map(float, ttest_rel(m, g))
    estimate, error = mean_sem(m - g)
    half_width = float(student_t.ppf(0.975, len(d) - 1) * error) if len(d) > 1 else np.nan
    rows.append({"Metric": metric, "Gratings_mean": gm, "Gratings_sem": gs, "Movie_mean": mm, "Movie_sem": ms,
                 "t_t": tval, "t_p": p, "n_pairs": len(d), "test_type": "paired_t", "status": status,
                 "estimate": estimate, "estimate_sem": error, "ci95_low": estimate - half_width, "ci95_high": estimate + half_width})

