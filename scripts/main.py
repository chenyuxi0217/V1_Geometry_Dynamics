def make_matched_sampling_plans(m_table, unit_ids, session_id, R, by_direction):
    movie_ids = np.sort(m_table["source_id"].unique().astype(np.int64))
    lookup = {(int(row.source_id), int(row.identity)): pos for pos, row in enumerate(m_table.itertuples())}
    if len(lookup) != len(m_table) or len(m_table) != len(movie_ids) * MOVIE_N_SEGMENTS:
        raise ValueError("Movie repeat/segment grid is incomplete or duplicated.")
    plans = []
    for draw in range(N_SUBSAMPLING):
        seed = stable_seed("session_sampling", session_id, draw)
        rng = np.random.RandomState(seed)
        neurons = rng.choice(len(unit_ids), size=GLOBAL_N, replace=False)
        gpos = np.stack([rng.choice(by_direction[float(ori)], size=R, replace=False) for ori in GRATING_ORIENTATIONS])
        segments = np.sort(rng.choice(MOVIE_N_SEGMENTS, size=N_STIM_IDENTITIES, replace=False))
        movie_repeats = np.sort(rng.choice(movie_ids, size=R, replace=False))
        mpos = np.array([[lookup[(int(rid), int(seg))] for rid in movie_repeats] for seg in segments], dtype=int)
        plans.append({"draw": draw, "seed": seed, "unit_positions": neurons, "g_positions": gpos, "m_positions": mpos,
                      "movie_segments": segments, "movie_repeats": movie_repeats})
    return plans

def get_neuron_count_cohort():
    sizes = list(NEURON_COUNT_VALUES)
    session_lists = {40: SESSION_IDS_40, 50: SESSION_IDS_50, 60: SESSION_IDS_60}
    cohort = list(session_lists[max(sizes)])
    if not cohort or len(cohort) != len(set(cohort)):
        raise ValueError("The largest-N session list must be nonempty and contain no duplicates.")
    if not set(cohort).issubset(SESSION_IDS_40) or any(not set(cohort).issubset(session_lists[n]) for n in sizes):
        raise ValueError("The common cohort must be included in the main list and each tested N list.")
    return cohort


def analyze_neuron_count_bin(g_all, m_all, unit_ids, plans, g_speed, m_speed, session_id, bin_ms):
    sizes = list(NEURON_COUNT_VALUES)
    if session_id not in get_neuron_count_cohort(): raise ValueError("Session is outside the common N-sensitivity cohort.")
    if len(unit_ids) < max(sizes):
        raise ValueError(f"Session {session_id}: found {len(unit_ids)} eligible units, but at least {max(sizes)} are required. Check the fixed session lists and unit filters.")
    if not plans or len(plans) != N_SUBSAMPLING: raise ValueError("Unexpected number of sampling plans.")
    if len(set(plan['draw'] for plan in plans)) != len(plans): raise ValueError("Duplicate draw IDs.")
    T = n_bins_for(ANALYSIS_WINDOW_S, bin_ms / 1000.0)
    if g_all.shape[1:] != (T, len(unit_ids)) or m_all.shape[1:] != (T, len(unit_ids)):
        raise ValueError("Sensitivity bin/neuron axes disagree with the original binning.")
    R = plans[0]["g_positions"].shape[1]
    rows_by_n = {n: [] for n in sizes}
    spectra = {n: {s: [] for s in ("g", "m")} for n in sizes}
    print(f"    Neuron-count sensitivity: {session_id}, {bin_ms} ms, N={sizes}")
    for plan in plans:
        base = np.asarray(plan["unit_positions"], dtype=int)
        if len(base) != GLOBAL_N or len(np.unique(base)) != GLOBAL_N:
            raise ValueError("The primary sample must contain exactly 40 distinct neurons.")
        remaining = np.setdiff1d(np.arange(len(unit_ids)), base, assume_unique=True)
        extra_rng = np.random.RandomState(stable_seed("neuron_count_extension", session_id, plan["draw"]))
        expanded = np.r_[base, extra_rng.permutation(remaining)]
        speed_g = mean_sem(g_speed[plan["g_positions"].ravel()])[0]
        speed_m = mean_sem(m_speed[plan["m_positions"].ravel()])[0]
        for n in sizes:
            idx = expanded[:n]
            g_identity = g_all[plan["g_positions"]][:, :, :, idx].astype(np.float64)
            m_identity = m_all[plan["m_positions"]][:, :, :, idx].astype(np.float64)
            if g_identity.shape != (N_STIM_IDENTITIES, R, T, n) or m_identity.shape != g_identity.shape:
                raise ValueError("Matched stimulus/window structure changed across neuron counts.")
            row = {"subsampling_iter": plan["draw"], "grating_speed_mean": speed_g,
                   "movie_speed_mean": speed_m, "delta_speed": speed_m - speed_g}
            fits, quality, eigens, full_taus, retained, complete = {}, {}, {}, {}, {}, {}
            for stim, identity in (("g", g_identity), ("m", m_identity)):
                trials = identity.reshape(-1, T, n)
