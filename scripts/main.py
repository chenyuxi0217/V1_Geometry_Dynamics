def build_transition_pairs(trials):
    X = validate_trials(trials)
    return X[:, :-1, :].reshape(-1, X.shape[-1]), X[:, 1:, :].reshape(-1, X.shape[-1])

def fit_full_linear_model(trials):
    X = validate_trials(trials)
    scaler = StandardScaler().fit(X.reshape(-1, X.shape[-1]))
    x, y = build_transition_pairs(X)
    x, y = scaler.transform(x), scaler.transform(y)
    model = LinearRegression(fit_intercept=True).fit(x, y)
    centered_x = x - x.mean(axis=0)
    singular = np.linalg.svd(centered_x, compute_uv=False)
    rank = int(model.rank_)
    condition = float(singular[0] / singular[-1]) if singular[-1] > 0 else np.inf
    qc = {"design_rank": rank, "design_condition_number": condition, "n_transition_pairs": len(x),
          "n_zero_variance_units": int(np.sum(scaler.var_ <= VAR_EPS)),
          "intercept_norm": float(np.linalg.norm(model.intercept_)), "full_rank": rank == X.shape[-1]}
    return model, scaler, qc

def compute_spectrum(W, bin_ms):
    W = np.asarray(W, dtype=np.float64)
    if W.ndim != 2 or W.shape[0] != W.shape[1] or not np.isfinite(W).all(): raise ValueError("Invalid W matrix.")
    eigenvalues = eigvals(W)
    moduli = np.abs(eigenvalues)
    valid = np.isfinite(moduli) & (moduli < 1.0) & (moduli > MIN_EIG_MODULUS)
    taus = np.full(moduli.shape, np.nan)
    taus[valid] = -float(bin_ms) / np.log(moduli[valid])
    ordered = np.sort(taus[np.isfinite(taus) & (taus > 0)])[::-1]
    complete = len(ordered) >= TOP_MODES
    retained = ordered[:TOP_MODES].copy() if complete else np.full(TOP_MODES, np.nan)
    return eigenvalues, taus, retained, complete


def spectrum_summary(taus):
    a = np.asarray(taus, dtype=float)
    complete = a.shape == (TOP_MODES,) and np.isfinite(a).all() and (a > 0).all() and np.all(np.diff(a) <= 1e-8)
    if not complete: return dict.fromkeys(SCALAR_KEYS, np.nan), dict.fromkeys(SHAPE_KEYS, np.nan)
    slow = float(a[SLOW_TAIL_RANKS[0] - 1:SLOW_TAIL_RANKS[1]].mean())
    slower_half = float(a[SLOWER_HALF_RANKS[0] - 1:SLOWER_HALF_RANKS[1]].mean())
    lower = float(a[LOWER_HALF_RANKS[0] - 1:LOWER_HALF_RANKS[1]].mean())
    ranks = np.arange(1, TOP_MODES + 1, dtype=float)
    centered_ranks = ranks - ranks.mean()
    slope = float(np.dot(centered_ranks, np.log(a)) / np.dot(centered_ranks, centered_ranks))
    y = np.log(a)
    fitted = y.mean() + slope * (ranks - ranks.mean())
    denominator = np.sum((y - y.mean()) ** 2)
    fit_r2 = float(1 - np.sum((y - fitted) ** 2) / denominator) if denominator > VAR_EPS else np.nan
    return ({"mean": float(a.mean()), "median": float(np.median(a)), "max": float(a[0]), "min": float(a[-1])},
            {
            "slow3_mean": slow, "lower10_mean": lower, "slow_lower_ratio": slow / lower,
            "slow_lower_logratio": float(np.log(slow / lower)), "log_spectrum_slope": slope, "log_spectrum_fit_r2": fit_r2,
            "slow10_mean": slower_half, "half_ratio": slower_half / lower, "half_logratio": float(np.log(slower_half / lower))})


def calculate_r2_np(true_y, pred_y, return_count=False):
    true_y, pred_y = np.asarray(true_y, dtype=float), np.asarray(pred_y, dtype=float)
    if true_y.shape != pred_y.shape or true_y.ndim != 2: raise ValueError("Incompatible target/prediction arrays.")
    finite = np.isfinite(true_y).all(axis=0) & np.isfinite(pred_y).all(axis=0)
    ss_res = np.sum((true_y - pred_y) ** 2, axis=0)
    ss_tot = np.sum((true_y - np.mean(true_y, axis=0)) ** 2, axis=0)
    valid = finite & (ss_tot > 1e-4)
    score = float(np.mean(1 - ss_res[valid] / ss_tot[valid])) if valid.any() else np.nan
    return (score, int(valid.sum())) if return_count else score

def neuron_wise_shuffle(Y, seed):
    rng = np.random.RandomState(seed)
    result = np.asarray(Y, dtype=float).copy()
    for col in range(result.shape[1]): result[:, col] = result[rng.permutation(len(result)), col]
    return result

