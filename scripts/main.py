def collect_subject_metadata(session, session_id):
    record = {"session_id": session_id, "specimen_name": "", "sex": "", "subject_metadata_status": "ok"}
    missing = []
    for field in ("specimen_name", "sex"):
        try:
            value = getattr(session, field)
            if value is None or not pd.api.types.is_scalar(value) or pd.isna(value) or not str(value).strip():
                raise ValueError("missing or non-scalar value")
            record[field] = str(value).strip()
        except Exception as exc:
            missing.append(field)
            warnings.warn(f"Session {session_id}: cannot read recorded {field} ({exc}); leave the metadata blank.")
    if missing: record["subject_metadata_status"] = "missing_" + "_and_".join(missing)
    return record


def validate_session_bin_grid(frame, session_ids, bin_widths, name):
    keys = ["session_id", "bin_ms"]
    missing_columns = set(keys) - set(frame.columns)
    if missing_columns: raise ValueError(f"{name}: missing key columns {sorted(missing_columns)}.")
    values = frame[keys].apply(pd.to_numeric, errors="raise").to_numpy(dtype=float)
    if not np.isfinite(values).all() or not np.equal(values, np.floor(values)).all():
        raise ValueError(f"{name}: session/bin keys must be finite integers.")
    actual_rows = [tuple(row) for row in values.astype(np.int64)]
    if len(actual_rows) != len(set(actual_rows)): raise ValueError(f"{name}: duplicate session/bin rows.")
    expected = {(int(sid), int(b)) for sid in session_ids for b in bin_widths}
    actual = set(actual_rows)
    if actual != expected:
        raise RuntimeError(f"{name}: incomplete planned session/bin grid. Missing={sorted(expected - actual)}; "
                           f"unexpected={sorted(actual - expected)}. This run has not exported results; "
                           "any existing files belong to an earlier run.")


def stable_seed(*parts):
    payload = "|".join(map(str, (BASE_SEED,) + parts)).encode("utf-8")
    return int.from_bytes(hashlib.sha256(payload).digest()[:4], "little")

def mean_sem(values):
    a = np.asarray(values, dtype=np.float64)
    a = a[np.isfinite(a)]
    if not len(a): return np.nan, np.nan
    return float(a.mean()), float(a.std(ddof=1) / np.sqrt(len(a))) if len(a) > 1 else np.nan

def mean_sd_n(values):
    a = np.asarray(values, dtype=np.float64)
    a = a[np.isfinite(a)]
    if not len(a): return np.nan, np.nan, 0
    return float(a.mean()), float(a.std(ddof=1)) if len(a) > 1 else np.nan, len(a)

def finite_frame(df, columns):
    missing = set(columns) - set(df.columns)
    if missing: raise ValueError(f"Missing required columns: {sorted(missing)}")
    d = df[columns].apply(pd.to_numeric, errors="coerce")
    return d.replace([np.inf, -np.inf], np.nan).dropna().reset_index(drop=True)

def validate_trials(X):
    X = np.asarray(X, dtype=np.float64)
    if X.ndim != 3 or min(X.shape) < 1 or X.shape[1] < 2: raise ValueError(f"Invalid trial shape: {X.shape}")
    if not np.isfinite(X).all(): raise ValueError("Trial data contain NaN or infinity.")
    return X

def n_bins_for(duration, dt):
    n = int(round(duration / dt))
    if n < 2 or not np.isclose(n * dt, duration, rtol=0, atol=TIME_TOL_S):
        raise ValueError(f"Duration {duration} s is not divisible by bin width {dt} s.")
    return n

def normalize_tokens(value):
    if isinstance(value, (list, tuple, set, np.ndarray)):
        out = []
        for item in value: out.extend(normalize_tokens(item))
        return out
    if value is None: return []
    if isinstance(value, bytes): value = value.decode("utf-8")
    if isinstance(value, str):
        s = value.strip()
        if s.startswith(("[", "(")):
            try: return normalize_tokens(ast.literal_eval(s))
            except (ValueError, SyntaxError): pass
        return [s]
    if isinstance(value, (float, np.floating)):
        if not np.isfinite(value): return []
        if value.is_integer(): return [str(int(value))]
    return [str(value)]

def interval_overlaps(starts, stops, invalid_intervals):
    starts, stops = np.asarray(starts, dtype=float), np.asarray(stops, dtype=float)
    mask = np.zeros(starts.shape, dtype=bool)
    for lo, hi in invalid_intervals:
        mask |= (starts < hi) & (stops > lo)
    return mask

def relevant_invalid_intervals(session, eligible_units, presentations, session_id):
    invalid = session.invalid_times
    if invalid is None: raise ValueError("invalid_times is unavailable; cannot verify recording coverage.")
    probes = session.probes
    all_probe_tokens, eligible_tokens = set(), set()
    unit_probe_column = "probe_id" if "probe_id" in eligible_units else "ecephys_probe_id"
    if unit_probe_column not in eligible_units and len(invalid):
        raise ValueError("Cannot map eligible units to probes for invalid-interval filtering.")
    eligible_ids = set(normalize_tokens(eligible_units[unit_probe_column].unique())) if unit_probe_column in eligible_units else set()
    for pid, row in probes.iterrows():
        tokens = set(normalize_tokens(pid))
        for col in ("description", "name", "probe_name"):
            if col in row: tokens.update(normalize_tokens(row[col]))
        tokens = {s.lower() for s in tokens}
        all_probe_tokens.update(tokens)
        if str(pid) in eligible_ids: eligible_tokens.update(tokens)
    eligible_tokens.update(s.lower() for s in eligible_ids)
    intervals, audit = [], []
    for invalid_id, row in invalid.iterrows():
        lo, hi = float(row["start_time"]), float(row["stop_time"])
        if not np.isfinite([lo, hi]).all() or hi <= lo: raise ValueError(f"Malformed invalid interval {invalid_id}.")
        tokens = {s.lower() for s in normalize_tokens(row.get("tags", []))}
        if "optotagging" in tokens and not tokens.intersection({"stimulus", "all_probes"}):
            apply, reason = False, "optotagging_only"
        elif tokens.intersection({"stimulus", "all_probes", "ecephyssession"}):
            apply, reason = True, "session_or_stimulus_scope"
        elif tokens.intersection(eligible_tokens):
            apply, reason = True, "eligible_probe_scope"
        elif tokens.intersection(all_probe_tokens):
            apply, reason = False, "unrelated_probe_scope"
        else:
            apply, reason = True, "unknown_scope_conservatively_excluded"
            warnings.warn(f"Session {session_id}: unknown invalid-time tags {tokens}; exclude overlapping windows.")
        audit.append({"session_id": session_id, "invalid_id": str(invalid_id), "start_time": lo, "stop_time": hi,
                      "tags": "|".join(sorted(tokens)), "applied": apply, "reason": reason})
        if apply: intervals.append((lo, hi))
    masked = presentations[presentations["stimulus_name"] == "invalid_presentation"]
    for pid, row in masked.iterrows():
        lo, hi = float(row["start_time"]), float(row["stop_time"])
        if not np.isfinite([lo, hi]).all() or hi <= lo: raise ValueError("Invalid masked presentation boundaries.")
        intervals.append((lo, hi))
        audit.append({"session_id": session_id, "invalid_id": f"presentation_{pid}", "start_time": lo, "stop_time": hi,
                      "tags": "invalid_presentation", "applied": True, "reason": "masked_stimulus_presentation"})
    return np.asarray(intervals, dtype=float).reshape(-1, 2), audit

def build_movie_repeats(presentations, session_id):
    movie = presentations[presentations["stimulus_name"] == "natural_movie_one"].copy()
    if "frame" not in movie: raise ValueError("Movie table has no frame column; cannot safely infer repeats.")
    movie["_frame"] = pd.to_numeric(movie["frame"], errors="coerce")
    movie = movie.sort_values("start_time", kind="stable")
    if movie.empty: return [], []
    if not np.isfinite(movie[["start_time", "stop_time", "_frame"]].to_numpy(dtype=float)).all():
        raise ValueError("Natural-movie rows contain missing frame IDs or times.")
    frames = movie["_frame"].to_numpy(dtype=float)
    starts = movie["start_time"].to_numpy(dtype=float)
    breaks = np.flatnonzero((np.diff(frames) <= 0) | (np.diff(starts) > 0.2)) + 1
    groups = np.split(np.arange(len(movie)), breaks)
    repeats, audit = [], []
    for group in groups:
        table = movie.iloc[group]
        f = table["_frame"].to_numpy(dtype=float)
        s, e = table["start_time"].to_numpy(dtype=float), table["stop_time"].to_numpy(dtype=float)
        rid = int(table.index[0])
        reasons = []
        if len(f) != MOVIE_N_FRAMES or not np.array_equal(f, np.arange(MOVIE_N_FRAMES)):
            reasons.append("incomplete_or_nonconsecutive_frame_sequence")
        if np.any(e <= s) or np.any(e - s > MAX_MOVIE_FRAME_DURATION_S): reasons.append("abnormal_frame_duration")
        if len(s) > 1 and np.any(np.abs(s[1:] - e[:-1]) > FRAME_GAP_TOL_S): reasons.append("frame_coverage_gap_or_overlap")
        duration = float(e[-1] - s[0])
        if abs(duration - MOVIE_DURATION_S) > MOVIE_DURATION_TOL_S: reasons.append("abnormal_total_duration")
        needed_end = float(s[0] + DROP_ONSET_S + MOVIE_N_SEGMENTS * ANALYSIS_WINDOW_S)
        if needed_end > e[-1] + TIME_TOL_S: reasons.append("insufficient_analysis_coverage")
        drift = float(np.max(np.abs((s - s[0]) - f / MOVIE_FRAME_RATE_HZ)))
        audit.append({"session_id": session_id, "movie_repeat_id": rid, "n_frames": len(f), "start_time": s[0],
                      "stop_time": e[-1], "duration_s": duration, "max_nominal_frame_drift_s": drift,
                      "sequence_valid": not reasons, "reason": "|".join(reasons) or "valid"})
        if not reasons: repeats.append({"repeat_id": rid, "start_time": float(s[0]), "stop_time": float(e[-1])})
    return repeats, audit

def prepare_windows(session, units, session_id):
    presentations = session.stimulus_presentations
    for name in ("stimulus_name", "start_time", "stop_time", "orientation", "temporal_frequency"):
        if name not in presentations: raise ValueError(f"Missing stimulus-table column: {name}")
    intervals, interval_audit = relevant_invalid_intervals(session, units, presentations, session_id)
    window_audit = []
    gratings = presentations[presentations["stimulus_name"] == "drifting_gratings"].copy().sort_values("start_time")
    ori = pd.to_numeric(gratings["orientation"], errors="coerce").to_numpy(dtype=float)
    tf = pd.to_numeric(gratings["temporal_frequency"], errors="coerce").to_numpy(dtype=float)
    mask = np.isfinite(ori) & np.isfinite(tf) & np.isclose(tf, GRATING_TEMPORAL_FREQUENCY_HZ, rtol=0, atol=1e-8)
    mask &= np.any(np.isclose(ori[:, None], GRATING_ORIENTATIONS[None, :], rtol=0, atol=1e-8), axis=1)
    gratings = gratings.iloc[np.flatnonzero(mask)].copy()
    gratings["orientation"] = ori[mask]
    g_rows = []
    for pid, row in gratings.iterrows():
        start, source_stop = float(row["start_time"]), float(row["stop_time"])
        lo, hi = start + DROP_ONSET_S, start + DROP_ONSET_S + ANALYSIS_WINDOW_S
        reason = "valid"
        if not np.isfinite([start, source_stop]).all() or hi > source_stop + TIME_TOL_S: reason = "insufficient_stimulus_coverage"
        elif interval_overlaps([lo], [hi], intervals)[0]: reason = "overlaps_invalid_interval"
        rec = {"session_id": session_id, "stimulus_class": "Grating", "source_id": int(pid), "identity": float(row["orientation"]),
               "start_time": lo, "stop_time": hi, "source_stop_time": source_stop, "included": reason == "valid", "reason": reason}
        window_audit.append(rec)
        if reason == "valid": g_rows.append(rec.copy())
    g_table = pd.DataFrame(g_rows)
    repeats, repeat_audit = build_movie_repeats(presentations, session_id)
    m_rows, valid_repeats = [], []
    for repeat in repeats:
        starts = repeat["start_time"] + DROP_ONSET_S + np.arange(MOVIE_N_SEGMENTS) * ANALYSIS_WINDOW_S
        stops = starts + ANALYSIS_WINDOW_S
        bad = interval_overlaps(starts, stops, intervals)
        repeat_ok = not bad.any()
        for j, (lo, hi) in enumerate(zip(starts, stops)):
            reason = "valid" if repeat_ok else ("overlaps_invalid_interval" if bad[j] else "repeat_excluded_for_common_identity_pool")
            rec = {"session_id": session_id, "stimulus_class": "Movie", "source_id": repeat["repeat_id"], "identity": j,
                   "start_time": lo, "stop_time": hi, "source_stop_time": repeat["stop_time"], "included": repeat_ok, "reason": reason}
            window_audit.append(rec)
            if repeat_ok: m_rows.append(rec.copy())
        if repeat_ok: valid_repeats.append(repeat)
        for rec in repeat_audit:
            if rec["movie_repeat_id"] == repeat["repeat_id"]:
                rec["recording_valid_for_all_segments"] = repeat_ok
    m_table = pd.DataFrame(m_rows)
    return g_table, m_table, window_audit, repeat_audit, interval_audit, len(repeats), len(valid_repeats)

def running_speed_for_windows(running, windows):
    required = ["start_time", "end_time", "velocity"]
    for col in required:
        if col not in running: raise ValueError(f"Missing running-speed column: {col}")
    data = running[required].apply(pd.to_numeric, errors="coerce").to_numpy(dtype=float)
    valid = np.isfinite(data).all(axis=1) & (data[:, 1] > data[:, 0])
    data = data[valid]
    means, coverage = [], []
    for row in windows.itertuples():
        overlap = np.maximum(0.0, np.minimum(data[:, 1], row.stop_time) - np.maximum(data[:, 0], row.start_time))
        total = overlap.sum()
        coverage.append(float(total / ANALYSIS_WINDOW_S))
        means.append(float(np.dot(overlap, data[:, 2]) / total) if total > 0 else np.nan)
    return np.asarray(means), np.asarray(coverage)

def bin_windows(spike_times, windows, unit_ids, bin_ms):
    dt = float(bin_ms) / 1000.0
    T = n_bins_for(ANALYSIS_WINDOW_S, dt)
    starts, stops = windows["start_time"].to_numpy(dtype=float), windows["stop_time"].to_numpy(dtype=float)
    if not np.isfinite(np.r_[starts, stops]).all(): raise ValueError("Nonfinite window boundaries.")
    if not np.allclose(stops - starts, ANALYSIS_WINDOW_S, rtol=0, atol=TIME_TOL_S): raise ValueError("Unequal analysis-window durations.")
    edges = starts[:, None] + np.arange(T + 1, dtype=float)[None, :] * dt
    edges[:, -1] = stops
    result = np.empty((len(windows), T, len(unit_ids)), dtype=np.float32)
    for col, uid in enumerate(unit_ids):
        if uid not in spike_times: raise ValueError(f"Missing spike-time record for unit {uid}; do not treat as silence.")
        spikes = np.asarray(spike_times[uid], dtype=np.float64)
        if spikes.ndim != 1 or not np.isfinite(spikes).all() or np.any(np.diff(spikes) < 0):
            raise ValueError(f"Nonfinite or unsorted spike times for unit {uid}.")
        # Both boundaries use side='left': all bins are [left, right).
        positions = np.searchsorted(spikes, edges, side="left")
        result[:, :, col] = np.diff(positions, axis=1)
    return result


